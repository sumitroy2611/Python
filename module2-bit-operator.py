# AND(&) bit operator
var1 = 1
var2 = 0
print(var1&var2)

# OR(|) bit operator
var1 = 1
var2 = 0
print(var1|var2)

# XOR(^) bit operator
var1 = 1
var2 = 0
print(var1^var2)

# Negation(~) bit operator
var1 = 0
print(~var1)

# Left shift(<<) bit operator
var1 = 2
print(var1 << 2)

# right shift(>>) bit operator
var1 = 20
print(var1 >> 2)
